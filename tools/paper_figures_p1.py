#!/usr/bin/env python3
"""
TASK P.2 -- figures 3, 4 and 6 (the ones that depend on the P.1 baselines or on the calibration pass).

    python -m tools.paper_figures_p1 --out results/paper/figures

  fig03  per-class IoU, every class scored on the test set, the proposed model against each baseline that finished (results/taskP/baselines.json)
  fig04  per-sequence mIoU on the 4 test sequences, grouped by model (the spread between sequences against the spread between models)
  fig06  reliability: (a) segmenter pixel confidence before and after temperature scaling (results/paper/calibration_pixels.json, from tools/calibration_pixels.py),
         (b) the gate's predicted score against the instrument IoU actually achieved, in 10 score bins, test frames (results/taskC/per_frame_scores.csv)

A figure whose input does not exist is not drawn and is listed under "missing"; nothing is estimated. Same style, palette and registry as tools/paper_figures.py (the README is regenerated by it).
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import sys
import traceback

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))  # repo root; the IDE's checker (Python 3.14, never runs this line) reports "unresolved import" below, the script resolves it at run time

import tools.paper_figures as PF  # noqa: E402  (style, palette, save(), registry)
from tools.paper_figures import OI, W1, W2, J, plt, save  # noqa: E402

SHORT = {"Ours: CAFormer-S18 + FPN": "Ours (CAFormer-S18)", "DeepLabV3+ (ResNet-18)": "DeepLabV3+ (R18)", "SegFormer-B0": "SegFormer-B0", "U-Net (classic, from scratch)": "U-Net (scratch)"}
ORDER = ["Ours: CAFormer-S18 + FPN", "DeepLabV3+ (ResNet-18)", "SegFormer-B0", "U-Net (classic, from scratch)"]
COL = {"Ours: CAFormer-S18 + FPN": OI["blue"], "DeepLabV3+ (ResNet-18)": OI["vermillion"], "SegFormer-B0": OI["green"], "U-Net (classic, from scratch)": OI["orange"]}
HATCH = {"Ours: CAFormer-S18 + FPN": "", "DeepLabV3+ (ResNet-18)": "//", "SegFormer-B0": "..", "U-Net (classic, from scratch)": "xx"}
SRC = "results/taskP/baselines.json"


def models():
    B = J(SRC)
    ms = sorted(B["models"], key=lambda m: ORDER.index(m["label"]) if m["label"] in ORDER else 99)
    absent = [u["label"] for u in B.get("unavailable", [])]
    return B, ms, absent


def absent_note(absent):
    return (" Not shown (training did not finish; see results/taskP/baselines.json): " + ", ".join(absent) + ".") if absent else ""


def fig3():
    B, ms, absent = models()
    names = [n for n, v in ms[0]["per_class"].items() if v["iou"] is not None]
    x = np.arange(len(names))
    w = 0.8 / len(ms)
    fig, ax = plt.subplots(figsize=(W2, 2.5))
    for i, m in enumerate(ms):
        v = [m["per_class"][n]["iou"] if m["per_class"][n]["iou"] is not None else 0 for n in names]
        ax.bar(x + (i - (len(ms) - 1) / 2) * w, v, w, color=COL[m["label"]], hatch=HATCH[m["label"]], edgecolor="white", linewidth=0.3, label=SHORT[m["label"]])
    ax.set_xticks(x)
    ax.set_xticklabels([n.replace("-", "-\n") if len(n) > 11 else n for n in names], rotation=0)
    ax.set_ylabel("IoU (official rule)")
    ax.set_ylim(0, 1.0)
    ax.legend(ncol=len(ms), loc="upper right")
    cap = (f"Per-class IoU on the 997 test frames of the 4 official test sequences under the official rule (a class is scored only on frames where the ground truth contains it), for the proposed model and the "
           f"baselines trained here under one recipe ({', '.join(SHORT[m['label']] for m in ms)}). A class with no ground truth in the test set is not drawn. Thin and rare classes (thread, needle) separate "
           f"the models least reliably; one training run per model, so differences of a few points are within run-to-run variation.{absent_note(absent)} Source: {SRC}.")
    save(fig, PF_OUT, "fig03_per_class_baselines", "Per-class IoU, proposed model against baselines", cap, [SRC])


def fig4():
    B, ms, absent = models()
    seqs = sorted(ms[0]["per_sequence"], key=lambda s: s)
    x = np.arange(len(seqs))
    w = 0.8 / len(ms)
    fig, ax = plt.subplots(figsize=(W1 + 0.3, 2.4))
    for i, m in enumerate(ms):
        ax.bar(x + (i - (len(ms) - 1) / 2) * w, [m["per_sequence"][s] for s in seqs], w, color=COL[m["label"]], hatch=HATCH[m["label"]], edgecolor="white", linewidth=0.3, label=SHORT[m["label"]])
    ax.set_xticks(x)
    ax.set_xticklabels([s.replace("test/", "") for s in seqs])
    ax.set_xlabel("test sequence")
    ax.set_ylabel("mIoU (official rule)")
    ax.set_ylim(0, 1.0)
    ax.legend(loc="lower center", bbox_to_anchor=(0.5, 1.0), ncol=3, frameon=False)   # above the axes: inside, it covered the bars of sequence 1
    allv = np.array([[m["per_sequence"][s] for s in seqs] for m in ms])
    cap = (f"mIoU of each model on each of the 4 official test sequences. The proposed model's per-sequence score ranges from {allv[0].min():.2f} to {allv[0].max():.2f}; the gap between sequences is larger than "
           f"the gap between models, which is why intervals in this study resample whole sequences.{absent_note(absent)} Source: {SRC}.")
    save(fig, PF_OUT, "fig04_per_sequence_baselines", "Per-sequence mIoU by model", cap, [SRC])


def fig6():
    pix = "results/paper/calibration_pixels.json"
    csvp = "results/taskC/per_frame_scores.csv"
    rows = [r for r in csv.DictReader(open(csvp, encoding="utf-8")) if r["group"] == "test"]
    s = np.array([float(r["gate: production (MLP; 9 indicators)"]) for r in rows])
    y = np.array([float(r["instrument_iou_risk_label"]) for r in rows])
    have_pix = os.path.exists(pix)
    fig, axs = plt.subplots(1, 2 if have_pix else 1, figsize=(W2 if have_pix else W1 + 0.2, 2.6))
    axs = np.atleast_1d(axs)
    k = 0
    notes = []
    if have_pix:
        P = J(pix)
        ax = axs[0]
        ax.plot([0, 1], [0, 1], color=OI["grey"], lw=0.7, ls=":", label="perfect")
        for name, c, mk, lab in (("before", OI["vermillion"], "o", "T = 1"), ("after", OI["blue"], "s", f"T = {P['temperature_stored']:.2f}")):
            bs = [b for b in P[name]["bins"] if b["conf"] is not None and b["count"] >= 1000]
            ax.plot([b["conf"] for b in bs], [b["acc"] for b in bs], marker=mk, ms=3, color=c, label=f"{lab} (ECE {P[name]['ece']:.3f})")
        ax.set_xlabel("pixel confidence (max softmax)")
        ax.set_ylabel("pixel accuracy")
        ax.set_title("(a) segmenter", loc="left")
        ax.legend(loc="upper left")
        k = 1
        notes.append(f"(a) pixel-level reliability of the segmenter's softmax on {P['n_frames']} test frames ({P['n_pixels']/1e6:.0f} M pixels, 15 bins, bins with fewer than 1000 pixels omitted), "
                     f"before and after the stored temperature (T = {P['temperature_stored']:.3f}, fitted earlier on training data, not on test); ECE {P['before']['ece']:.3f} before and {P['after']['ece']:.3f} after")
    ax = axs[k]
    edges = np.quantile(s, np.linspace(0, 1, 11))
    idx = np.clip(np.searchsorted(edges, s, side="right") - 1, 0, 9)
    mx = [s[idx == b].mean() for b in range(10) if (idx == b).any()]
    my = [y[idx == b].mean() for b in range(10) if (idx == b).any()]
    ax.plot([0, 1], [0, 1], color=OI["grey"], lw=0.7, ls=":", label="perfect")
    ax.plot(mx, my, marker="o", ms=3, color=OI["blue"], label="gate")
    ax.set_xlabel("gate score (predicted instrument IoU)")
    ax.set_ylabel("achieved instrument IoU")
    ax.set_title("(b) gate" if k else "", loc="left")
    ax.legend(loc="upper left")
    notes.append(f"{'(b) ' if k else ''}the gate's score against the instrument IoU actually achieved, in 10 equal-count bins of the {len(s)} test frames; the gate is trained to regress this IoU and was not tuned on test. "
                 f"Mean score {s.mean():.3f} against mean achieved {y.mean():.3f}: the gate over-predicts on the test sequences in {sum(1 for a_, b_ in zip(mx, my) if a_ > b_)} of {len(mx)} bins (all but the lowest-scoring), "
                 "so its ranking can be used but its absolute values cannot be read as IoU")
    cap = "Calibration. " + ". ".join(n[0].upper() + n[1:] for n in notes) + ". " + ("" if have_pix else "The segmenter's pixel reliability before and after temperature scaling is not drawn here: results/paper/calibration_pixels.json does not exist yet (tools/calibration_pixels.py needs the GPU). ") + f"Sources: {csvp}" + (f", {pix}." if have_pix else ".")
    save(fig, PF_OUT, "fig06_reliability", "Reliability: segmenter before and after temperature scaling, and the gate", cap, [csvp] + ([pix] if have_pix else []))


PF_OUT = "results/paper/figures"


def main():
    global PF_OUT
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="results/paper/figures")
    ap.add_argument("--only", nargs="*", type=int, default=None)
    a = ap.parse_args()
    PF_OUT = a.out
    for k, fn in ((3, fig3), (4, fig4), (6, fig6)):
        if a.only and k not in a.only:
            continue
        try:
            fn()
        except Exception as e:  # noqa: BLE001 -- reported, never hidden
            PF.MISSING.append((k, f"{type(e).__name__}: {e}"))
            print(f"  FIGURE {k} NOT DRAWN: {type(e).__name__}: {e}")
            traceback.print_exc()
    reg_path = os.path.join(a.out, "_registry.json")
    reg = json.load(open(reg_path)) if os.path.exists(reg_path) else {}
    for n, t, srcs, c in PF.MADE:
        reg[n] = dict(title=t, sources=srcs, caption=c)
    json.dump(reg, open(reg_path, "w"), indent=1)
    print("made:", [m[0] for m in PF.MADE], " missing:", PF.MISSING)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
