#!/usr/bin/env python3
"""
Task B: every policy side by side, with the denominator stated for each column. Reads selector_results.json only
(nothing is recomputed).

    python -m tools.policy_table --selector results/task5/selector_results.json --out results/taskB

Columns (all in instrument IoU, class counts if in the ground truth OR the prediction, i.e. the quantity the action
data labels with):
  activation        % of ALL frames on which the policy changed the mask
  on flagged        mean IoU change over the flagged frames (the frames the gate routes), changed or not
  on corrected      mean IoU change over the frames the policy actually changed
  all frames        mean IoU change over every frame (= on flagged x flagged share for a policy that only acts on flagged frames)
  official, all     mean change of the official 12-class frame IoU over every frame (ground-truth-only class rule)
"""
import argparse, json, os

ORDER = ["oracle (routed)", "selector", "always-A1 (routed)", "always-A2 (routed)", "always-A3 (routed)",
         "always-fuse (routed)", "always-fuse (EVERY frame)", "always-fuse+refine (EVERY)"]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--selector", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    R = json.load(open(a.selector))
    os.makedirs(a.out, exist_ok=True)
    out, md = {}, ["# Policies side by side (generated by tools/policy_table.py from " + a.selector.replace("\\", "/") + ")\n"]
    for g, title in (("test", "Official test"), ("oof", "Out of fold (15 training sequences)")):
        n, nr = R[f"n_{g}" if g == "test" else "n_oof"], R[f"n_{g}_routed" if g == "test" else "n_oof_routed"]
        md.append(f"\n## {title}: {n} frames, {nr} flagged ({100*nr/n:.1f}%)\n")
        md.append("| policy | activation % of all | mean change on flagged | mean change on corrected | mean change, all frames | official 12-class change, all frames | harmful % of corrected |")
        md.append("|---|---|---|---|---|---|---|")
        out[g] = {}
        for p in ORDER:
            s = R[g][p]
            row = dict(activation_pct_of_all=s["activation_pct_of_all"], mean_on_flagged=s["mean_delta_routed"],
                       mean_on_corrected=s["mean_delta_when_corrected"], mean_all_frames=s["mean_delta_all_frames"],
                       official_all_frames=s["mean_delta_official_all_frames"], harmful_pct_of_corrected=s["harmful_rate_of_corrected"],
                       n_corrected=s["n_corrected"])
            out[g][p] = row
            md.append(f"| {p} | {row['activation_pct_of_all']:.1f} | {row['mean_on_flagged']:+.4f} | {row['mean_on_corrected']:+.4f} | "
                      f"{row['mean_all_frames']:+.4f} | {row['official_all_frames']:+.5f} | {row['harmful_pct_of_corrected']:.1f} |")
        o, a3, se = (R[g][k]["mean_delta_routed"] for k in ("oracle (routed)", "always-A3 (routed)", "selector"))
        out[g]["_headroom_on_flagged"] = dict(oracle=o, always_A3=a3, selector=se, oracle_minus_A3=o - a3, A3_minus_selector=a3 - se,
                                              selector_share_of_oracle=se / o, A3_share_of_oracle=a3 / o)
        md.append(f"\nOn flagged frames: oracle {o:+.4f}, always-A3 {a3:+.4f} ({100*a3/o:.0f}% of the oracle), selector {se:+.4f} ({100*se/o:.0f}% of the oracle). "
                  f"Headroom of the oracle over always-A3: {o-a3:+.4f}.\n")
    json.dump(out, open(os.path.join(a.out, "policy_table.json"), "w"), indent=1)
    open(os.path.join(a.out, "policy_table.md"), "w").write("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
